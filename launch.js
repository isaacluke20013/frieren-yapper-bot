const GEMINI_MODEL = 'gemini-3.5-flash-lite';
const QOTD_HISTORY_FILE = '/data/qotd-history.json';
const originalSend = Bot.prototype.send;

function loadQotdHistory() {
  try {
    if (!fs.existsSync(QOTD_HISTORY_FILE)) {
      return [];
    }

    const parsed = JSON.parse(
      fs.readFileSync(QOTD_HISTORY_FILE, 'utf8')
    );

    return Array.isArray(parsed?.questions)
      ? parsed.questions.filter(item => typeof item?.question === 'string')
      : [];
  } catch (err) {
    console.error('[qotd-ai] could not load history:', err.message);
    return [];
  }
}

function saveQotdHistory(entries) {
  try {
    fs.writeFileSync(
      QOTD_HISTORY_FILE,
      JSON.stringify({ questions: entries.slice(-60) }, null, 2),
      'utf8'
    );
  } catch (err) {
    console.error('[qotd-ai] could not save history:', err.message);
  }
}

function normalizeQuestion(text) {
  return String(text || '')
    .trim()
    .replace(/^QOTD\s*:\s*/i, '')
    .replace(/^[\-•*"'`\s]+/, '')
    .replace(/["'`\s]+$/, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function comparisonKey(text) {
  return normalizeQuestion(text)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

async function generateQotd() {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey) {
    throw new Error('GEMINI_API_KEY is missing');
  }

  const history = loadQotdHistory();
  const recent = history.slice(-40).map(item => item.question);
  const used = new Set(recent.map(comparisonKey));

  for (let attempt = 1; attempt <= 3; attempt++) {
    const prompt = [
      'Create exactly ONE fresh question of the day for a Frieren: Beyond Journey’s End fan community.',
      'Make it fun to answer and good for conversation in a community server.',
      'Vary the topic: characters, magic, travel, relationships, worldbuilding, funny hypotheticals, favorite moments, choices, or opinions.',
      'Keep it concise, ideally one sentence and under 220 characters.',
      'Do not include an answer, explanation, numbering, quotation marks, or the words “QOTD”.',
      'Avoid major manga spoilers and do not repeat or closely copy any recent question below.',
      recent.length
        ? `Recent questions to avoid:\n${recent.map((q, i) => `${i + 1}. ${q}`).join('\n')}`
        : 'There are no recent questions yet.'
    ].join('\n\n');

    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/${GEMINI_MODEL}:generateContent`,
      {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'x-goog-api-key': apiKey
        },
        body: JSON.stringify({
          contents: [
            {
              role: 'user',
              parts: [{ text: prompt }]
            }
          ],
          generationConfig: {
            temperature: 1.15,
            maxOutputTokens: 100
          }
        })
      }
    );

    if (!response.ok) {
      const detail = await response.text().catch(() => '');
      throw new Error(
        `Gemini HTTP ${response.status}${detail ? `: ${detail.slice(0, 250)}` : ''}`
      );
    }

    const json = await response.json();
    const question = normalizeQuestion(
      (json?.candidates?.[0]?.content?.parts || [])
        .map(part => part?.text || '')
        .join(' ')
    );

    const key = comparisonKey(question);

    if (
      question.length >= 10 &&
      question.length <= 300 &&
      key &&
      !used.has(key)
    ) {
      history.push({
        question,
        createdAt: new Date().toISOString()
      });
      saveQotdHistory(history);
      return question;
    }
  }

  throw new Error('Gemini repeated recent QOTDs three times');
}

Bot.prototype.send = async function patchedFrierenSend(
  channelId,
  content,
  opts = {}
) {
  const text = String(content ?? '');
  const match = text.match(/^\*\*QOTD #(\d+)\*\*/);

  if (!match) {
    return originalSend.call(this, channelId, content, opts);
  }

  const heading = match[0];

  try {
    const question = await generateQotd();
    return originalSend.call(
      this,
      channelId,
      `${heading}\n\n${question}`,
      opts
    );
  } catch (err) {
    console.error('[qotd-ai] generation failed:', err.message);
    return originalSend.call(
      this,
      channelId,
      `${heading}\n\n⚠️ I couldn't generate a new QOTD right now. Try \`/qotd\` again in a moment.`,
      opts
    );
  }
};

